"""Python-authored AppHost (preview): Django + HTMX polls on PostgreSQL.

The Aspire SDK in .aspire/modules is generated by `aspire restore`.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / ".aspire/modules"))

from aspire_app import create_builder  # noqa: E402

with create_builder() as builder:
    # PostgreSQL container plus a database. Referencing it injects POLLSDB_URI.
    db = builder.add_postgres("pg").add_database("pollsdb")

    # Django runs natively: Aspire creates a venv from src/requirements.txt and
    # runs run.py, which migrates, seeds, and serves with waitress on PORT.
    (
        builder.add_python_app("polls", "./src", "run.py")
        # Install into src/.venv rather than the AppHost's own .venv.
        .with_virtual_env(".venv")
        .with_pip()
        .with_reference(db)
        .wait_for(db)
        .with_http_endpoint(env="PORT")
        .with_http_health_check(path="/")
        .with_external_http_endpoints()
    )

    builder.build().run()
