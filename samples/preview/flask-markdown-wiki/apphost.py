"""Python-authored AppHost (preview): a Flask wiki container plus Redis.

This is the repository's Dockerfile example: the wiki is built from
src/Dockerfile and runs as a container. The Aspire SDK in .aspire/modules is
generated by `aspire restore`.
"""
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / ".aspire/modules"))

from aspire_app import create_builder  # noqa: E402

with create_builder() as builder:
    # Redis with a generated password and TLS. Referencing it injects CACHE_URI.
    cache = builder.add_redis("cache")

    (
        builder.add_dockerfile("wiki", "./src")
        # Forward a private package index to `pip install` in the image build, if set.
        .with_build_arg("PIP_INDEX_URL", os.environ.get("PIP_INDEX_URL", "https://pypi.org/simple/"))
        .with_reference(cache)
        .wait_for(cache)
        .with_otlp_exporter()
        .with_http_endpoint(target_port=8080, env="PORT")
        .with_http_health_check(path="/health")
        .with_external_http_endpoints()
    )

    builder.build().run()
